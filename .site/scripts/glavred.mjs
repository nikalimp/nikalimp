const COMPILED = RULES.map((r) => ({ ...r, rx: new RegExp(`(?<![\\p{L}-])(?:${r.re.join("|")})(?![\\p{L}])`, "giu") }));
const PASSIVE = /(?<![\p{L}])(?:был|была|было|были|будет|будут)\s+[а-яё]+(?:ан|ен|ён|т)(?:а|о|ы)?(?![\p{L}])/giu;
const VERBAL = /(?<![\p{L}])[а-яё]{4,}(?:ание|ение|ения|ению|ением|ании|ании|ация|ации|ацию|ацией)(?![\p{L}])/giu;

function clean(text) {
  return text
    .replace(/^---\n[\s\S]*?\n---\n/, (m) => "\n".repeat(m.split("\n").length - 1))
    .replace(/```[\s\S]*?```/g, (m) => "\n".repeat(m.split("\n").length - 1))
    .replace(/<[^>]+>|`[^`\n]*`|\]\([^)]*\)|https?:\/\/\S+|\[\[|\]\]/g, " ")
    .replace(/\u00A0/g, " ");
}

export function glavred(input) {
  const text = clean(input);
  const hits = [];
  const lines = text.split("\n");
  lines.forEach((line, i) => {
    for (const r of COMPILED) for (const m of line.matchAll(r.rx)) hits.push({ line: i + 1, word: m[0], cat: r.cat, tip: r.tip });
    for (const m of line.matchAll(PASSIVE)) hits.push({ line: i + 1, word: m[0], cat: "Пассивный залог", tip: "Кто сделал? Перестройте в активный залог" });
  });
  const sentences = text.split(/\n+/).filter((l) => !/^\s*(\||#)/.test(l)).flatMap((l) => l.split(/(?<=[.!?…][*_»")]*)\s+/)).map((s) => s.trim()).filter((s) => /\p{L}/u.test(s));
  const longSentences = [];
  for (const s of sentences) {
    const words = s.split(/\s+/).filter((w) => /\p{L}/u.test(w)).length;
    if (words > 25) longSentences.push({ words, text: s.slice(0, 90) + (s.length > 90 ? "…" : "") });
    const verbal = s.match(VERBAL) || [];
    if (verbal.length >= 3) hits.push({ line: 0, word: verbal.join(", "), cat: "Отглагольные существительные", tip: "Замените глаголами: «проведение анализа» → «анализируем»" });
  }
  const words = (text.match(/\p{L}+/gu) || []).length;
  const penalty = words ? ((hits.length + longSentences.length) / words) * 100 : 0;
  const score = Math.max(0, Math.min(10, 10 - penalty * 0.6)).toFixed(1);
  return { score: +score, words, hits, longSentences };
}

const isCli = process.argv[1]?.endsWith("glavred.mjs");
if (isCli) {
  const fs = await import("node:fs");
  const args = process.argv.slice(2);
  const file = args.find((a) => !a.startsWith("--"));
  const r = glavred(file ? fs.readFileSync(file, "utf8") : fs.readFileSync(0, "utf8"));
  if (args.includes("--json")) { console.log(JSON.stringify(r, null, 2)); process.exit(0); }
  console.log(`Оценка: ${r.score} / 10 · слов: ${r.words} · стоп-слов: ${r.hits.length} · длинных предложений: ${r.longSentences.length}`);
  console.log(r.score >= 8 ? "Чистый текст." : r.score >= 7 ? "Норма для сайта, но можно чище." : "Нужна редактура.");
  const byCat = {};
  for (const h of r.hits) (byCat[h.cat] ||= []).push(h);
  for (const [cat, list] of Object.entries(byCat)) {
    console.log(`\n${cat} (${list.length}) — ${list[0].tip}`);
    for (const h of list) console.log(`  ${h.line ? `стр. ${h.line}: ` : ""}${h.word}`);
  }
  if (r.longSentences.length) {
    console.log(`\nДлинные предложения (>25 слов) — разбейте`);
    for (const s of r.longSentences) console.log(`  ${s.words} сл.: ${s.text}`);
  }
}
