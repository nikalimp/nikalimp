// ——— Помощники ———

const ph = (v: string, placeholder: string) => (v.trim() ? v.trim() : `[${placeholder}]`);
const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

export function fmtDate(iso: string) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso);
  if (!m) return "[дата]";
  const months = ["января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября", "ноября", "декабря"];
  return `«${Number(m[3])}» ${months.at(Number(m[2]) - 1)} ${m[1]} г.`;
}

export function money(v: string) {
  const n = Number(v.replace(/[^\d.,]/g, "").replace(",", "."));
  if (!v.trim() || !Number.isFinite(n) || n <= 0) return "[сумма]";
  return `${n.toLocaleString("ru-RU", { maximumFractionDigits: 2 })} руб.`;
}

const num = (v: string, d: string) => (v.trim() && /^\d+$/.test(v.trim()) ? v.trim() : d);

function vatText(c: ContractConfig) {
  if (c.exec.type === "self") return "НДС не облагается: Исполнитель применяет налог на профессиональный доход";
  if (c.vat === "npd") return "НДС не облагается: Исполнитель применяет налог на профессиональный доход";
  if (c.vat === "usn") return "НДС не облагается в связи с применением Исполнителем упрощённой системы налогообложения";
  return `в том числе НДС ${c.vat}%`;
}

function role(p: Party, who: "Исполнитель" | "Заказчик") {
  const name = ph(p.name, p.type === "org" ? `название организации ${who === "Исполнитель" ? "Исполнителя" : "Заказчика"}` : `ФИО ${who === "Исполнитель" ? "Исполнителя" : "Заказчика"}`);
  if (p.type === "ip") return /^ип\s/i.test(name) ? name : `индивидуальный предприниматель ${name}`;
  if (p.type === "self") return `${name}, плательщик налога на профессиональный доход`;
  if (p.type === "person") return `физическое лицо ${name}`;
  return name;
}

function partyIntro(p: Party, who: "Исполнитель" | "Заказчик") {
  const ids = [
    p.inn.trim() && `ИНН ${p.inn.trim()}`,
    p.type === "ip" && p.ogrn.trim() && `ОГРНИП ${p.ogrn.trim()}`,
    p.type === "org" && p.ogrn.trim() && `ОГРН ${p.ogrn.trim()}`,
  ].filter(Boolean);
  const signer = p.type === "org" ? `, договор подписывает ${ph(p.position, "должность").toLowerCase()} ${ph(p.signer, "ФИО подписанта")}, основание полномочий — ${ph(p.basis, "Устав")}` : "";
  return `${role(p, who)}${ids.length ? ` (${ids.join(", ")})` : ""}${signer} (далее — «${who}»)`;
}

function requisites(p: Party, who: "Исполнитель" | "Заказчик") {
  const lines = [
    `${who}: ${cap(role(p, who))}`,
    p.inn.trim() && `ИНН ${p.inn.trim()}`,
    p.type === "ip" && p.ogrn.trim() && `ОГРНИП ${p.ogrn.trim()}`,
    p.type === "org" && p.ogrn.trim() && `ОГРН ${p.ogrn.trim()}`,
    p.type === "person" && p.passport.trim() && `Паспорт ${p.passport.trim()}`,
    p.address.trim() && `Адрес: ${p.address.trim()}`,
    p.account.trim() && `Р/с ${p.account.trim()}`,
    p.bank.trim() && `Банк: ${p.bank.trim()}`,
    p.bik.trim() && `БИК ${p.bik.trim()}`,
    p.corr.trim() && `К/с ${p.corr.trim()}`,
    p.email.trim() && `Email: ${p.email.trim()}`,
    p.phone.trim() && `Телефон: ${p.phone.trim()}`,
  ].filter(Boolean) as string[];
  const sign = p.type === "org" ? `${ph(p.position, "должность")} ________ / ${ph(p.signer, "ФИО")}` : `________ / ${ph(p.name, "ФИО")}`;
  return [...lines, "", sign].join("\n");
}

function numbered(sections: { title: string; items: (string | false | Block)[] }[]): Block[] {
  const out: Block[] = [];
  sections.forEach((s, i) => {
    const n = i + 1;
    out.push({ type: "h", text: `${n}. ${s.title}` });
    let k = 0;
    for (const it of s.items) {
      if (it === false) continue;
      if (typeof it === "string") out.push({ type: "p", n: `${n}.${++k}.`, text: it });
      else out.push(it);
    }
  });
  return out;
}

