export type Block =
  | { type: "h"; text: string }
  | { type: "p"; text: string; n?: string }
  | { type: "ul"; items: string[] }
  | { type: "table"; head: string[]; rows: string[][] };

export type Doc = { title: string; blocks: Block[] };

const ph = (v: string, placeholder: string) => (v.trim() ? v.trim() : `[${placeholder}]`);

export function normalizeUrl(v: string) {
  const s = v.trim().replace(/\s+/g, "");
  if (!s) return "";
  return /^https?:\/\//i.test(s) ? s.replace(/\/+$/, "") : `https://${s.replace(/\/+$/, "")}`;
}

function siteUrl(c: PolicyConfig) {
  return normalizeUrl(c.site) || "[адрес сайта]";
}
function policyUrl(c: PolicyConfig) {
  const own = normalizeUrl(c.policyUrl);
  if (own) return own;
  const s = normalizeUrl(c.site);
  return s ? `${s}/privacy` : "[адрес страницы с политикой]";
}
function consentUrl(c: PolicyConfig) {
  const own = normalizeUrl(c.consentUrl);
  if (own) return own;
  const s = normalizeUrl(c.site);
  return s ? `${s}/consent` : "[адрес страницы с согласием]";
}

export function operatorTitle(c: PolicyConfig) {
  const name = ph(c.operatorName, c.operatorType === "org" ? "название организации" : "ФИО");
  if (c.operatorType === "ip") return /^ип\s/i.test(name) ? name : `индивидуальный предприниматель ${name}`;
  return name;
}

function requisites(c: PolicyConfig) {
  const parts = [
    c.inn.trim() && `ИНН ${c.inn.trim()}`,
    c.ogrn.trim() && `${c.operatorType === "ip" ? "ОГРНИП" : "ОГРН"} ${c.ogrn.trim()}`,
    c.address.trim() && `адрес: ${c.address.trim()}`,
  ].filter(Boolean);
  return parts.length ? ` (${parts.join(", ")})` : "";
}

const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
const list = (items: string[]) => items.filter((s) => s.trim()).join("; ");
const email = (c: PolicyConfig) => ph(c.email, "email для связи");

function fmtDate(iso: string) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso);
  return m ? `${m[3]}.${m[2]}.${m[1]}` : iso.trim() || "[дата]";
}

// Нумерация: разделы 1, 2…, пункты 1.1, 1.2…
function numbered(sections: { title: string; items: (string | Block)[] }[]): Block[] {
  const out: Block[] = [];
  sections.forEach((s, i) => {
    const n = i + 1;
    out.push({ type: "h", text: `${n}. ${s.title}` });
    let k = 0;
    for (const it of s.items) {
      if (typeof it === "string") out.push({ type: "p", n: `${n}.${++k}.`, text: it });
      else out.push(it);
    }
  });
  return out;
}

