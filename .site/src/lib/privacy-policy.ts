const escHtml = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

export function linkify(escaped: string) {
  return escaped
    .replace(/\bhttps?:\/\/[^\s<>«»"]+[^\s<>«»".,;:)]/g, (u) => `<a href="${u}">${u}</a>`)
    .replace(/[\w.+-]+@[\w-]+\.[\w.-]*\w/g, (m) => `<a href="mailto:${m}">${m}</a>`);
}

export function toText(doc: Doc, fix: (s: string) => string = (s) => s) {
  const lines = [doc.title, ""];
  for (const b of doc.blocks) {
    if (b.type === "h") lines.push("", fix(b.text), "");
    else if (b.type === "p") lines.push(fix(b.n ? `${b.n} ${b.text}` : b.text));
    else if (b.type === "ul") b.items.forEach((i) => lines.push(`— ${fix(i)}`));
    else {
      b.rows.forEach((r, i) => {
        lines.push(`${i + 1})`);
        r.forEach((cell, j) => lines.push(`${b.head[j]}: ${fix(cell)}`));
        lines.push("");
      });
    }
  }
  return lines.join("\n").replace(/\n{3,}/g, "\n\n").trim() + "\n";
}

export function toHtml(doc: Doc, fix: (s: string) => string = (s) => s) {
  const t = (s: string) => linkify(escHtml(fix(s)));
  const parts = [`<h1>${t(doc.title)}</h1>`];
  for (const b of doc.blocks) {
    if (b.type === "h") parts.push(`<h2>${t(b.text)}</h2>`);
    else if (b.type === "p") parts.push(`<p>${b.n ? `${b.n} ` : ""}${t(b.text)}</p>`);
    else if (b.type === "ul") parts.push(`<ul>\n${b.items.map((i) => `  <li>${t(i)}</li>`).join("\n")}\n</ul>`);
    else
      parts.push(
        `<table>\n  <thead><tr>${b.head.map((h) => `<th>${t(h)}</th>`).join("")}</tr></thead>\n  <tbody>\n${b.rows.map((r) => `    <tr>${r.map((c) => `<td>${t(c).replace(/\n/g, "<br>")}</td>`).join("")}</tr>`).join("\n")}\n  </tbody>\n</table>`,
      );
  }
  return parts.join("\n");
}

